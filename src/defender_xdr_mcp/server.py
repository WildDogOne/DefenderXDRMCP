"""Builds and runs the Defender XDR MCP server.

The tool set itself is not hand-written: it's generated by FastMCP straight from Microsoft's own
Graph OpenAPI specs, trimmed to the operations this project exposes by scripts/fetch_spec.py, which
emits two specs split by API version:

- openapi/security_v1.generated.yaml - Graph **v1.0**: Incidents (list/get/update), Advanced Hunting
  (runHuntingQuery), custom detection rules (list/get).
- openapi/security_beta.generated.yaml - Graph **beta**: incident tasks and case management
  (cases read/update, comments, tasks) - operations that don't exist in v1.0.

The rule is v1.0 wherever the operation exists there (stable, production-supported) and beta only
for the rest; the legacy api.security.microsoft.com XDR host is never used (it is being retired).
Each spec carries its own `servers` entry and build_server() mounts one OpenAPI provider per
version, so every tool hits the right base URL. When Microsoft changes those endpoints, re-running
the generator picks it up - this file shouldn't need to change.

The specs ship as package data (src/defender_xdr_mcp/openapi/) rather than living outside the
package, and are loaded via importlib.resources rather than a path relative to this file's
location on disk. That's deliberate: `uv tool install` (and any other install path - a wheel, an
editable install, a zipped package) copies the *package* into an isolated environment but does not
carry along loose files that sit outside it, so a "few parents up from __file__" path breaks the
moment this stops being run straight out of a source checkout.

Toolsets (GRAPH_MCP_TOOLSETS, comma-separated, default "xdr"):
- xdr:   the generated Defender XDR tools (Graph v1.0 + beta).
- graph: three read-only tools that reach all of Graph (v1.0, beta opt-in) via search -> describe -> get
         (see graph_tools.py). Off by default to keep the agent's context small.
"""

from __future__ import annotations

import os
from collections.abc import Iterable
from importlib import resources
from typing import Any

import yaml
from dotenv import load_dotenv
from fastmcp import FastMCP
from fastmcp.server.providers.openapi import OpenAPIProvider
from fastmcp.server.providers.openapi.routing import MCPType, RouteMap

from .auth import GRAPH_ROOT, build_auth, build_http_client
from .graph_tools import register_graph_tools
from .odata_scalars import normalize_odata_scalars
from .patch_body import strip_patch_discriminator
from .schema_sanitize import sanitize_component

# Two generated specs, one per Graph API version. v1.0 where the operation exists there, beta only
# for what v1.0 lacks (incident tasks, case management). Each spec carries its own `servers` entry,
# and build_server() mounts one OpenAPI provider per version so each tool hits the right base URL.
SPEC_RESOURCE_V1 = resources.files("defender_xdr_mcp.openapi").joinpath("security_v1.generated.yaml")
SPEC_RESOURCE_BETA = resources.files("defender_xdr_mcp.openapi").joinpath("security_beta.generated.yaml")

TOOLSETS = ("xdr", "graph")
DEFAULT_TOOLSETS = ("xdr",)

# GET -> read-only tools (incidents, incident tasks, detection rules, cases and their sub-collections).
# PATCH -> mutating tools: UpdateIncidents, caseManagement_UpdateCases, caseManagement_cases_UpdateTasks.
# POST -> two kinds:
#   - runHuntingQuery: read-only against tenant data (it runs a KQL query and returns rows) but
#     modeled as POST by Graph because it's an action, not a resource fetch.
#   - caseManagement_cases_CreateActivities (add a comment) and caseManagement_cases_CreateTasks:
#     these write to the tenant.
# Every kept operation is mapped explicitly (rather than relying on FastMCP's default
# GET-is-a-tool heuristic). The HTTP method alone no longer separates reads from writes (POST is
# both), so the tenant-mutating tools are listed above and in the README: every PATCH, plus every
# POST except runHuntingQuery. Wire that into your MCP client's permission rules (e.g. Claude Code's
# permissions.allow/ask) the same way.
ROUTE_MAPS = [
    RouteMap(methods=["GET"], mcp_type=MCPType.TOOL),
    RouteMap(methods=["POST"], mcp_type=MCPType.TOOL),
    RouteMap(methods=["PATCH"], mcp_type=MCPType.TOOL),
]


def _customize_component(route: Any, component: Any) -> None:
    # Drop the generated output schema: it's the full nested Graph response model (~18 KB per
    # incident tool, ~90% of each tool's definition) and only serves to validate responses, which
    # the agent doesn't need. Responses still come back as structured JSON.
    component.output_schema = None
    # Graph's OData property names ($top, @odata.type, ...) contain characters the MCP tool
    # schema validator rejects - see schema_sanitize.py for why and how this is reversible.
    sanitize_component(route, component)
    # FastMCP serializes boolean query parameters with str() ($count=True), which Graph rejects -
    # see odata_scalars.py. Order-independent: the two hooks rewrite disjoint argument names.
    normalize_odata_scalars(route, component)
    # Graph rejects an update body that carries the resource's own @odata.type discriminator -
    # see patch_body.py. Runs after sanitize_component so it sees the sanitized name in the schema.
    strip_patch_discriminator(route, component)


def selected_toolsets() -> tuple[str, ...]:
    raw = os.environ.get("GRAPH_MCP_TOOLSETS", "")
    toolsets = tuple(t.strip().lower() for t in raw.split(",") if t.strip()) or DEFAULT_TOOLSETS
    unknown = sorted(set(toolsets) - set(TOOLSETS))
    if unknown:
        raise RuntimeError(f"Unknown GRAPH_MCP_TOOLSETS value(s) {unknown}; valid: {list(TOOLSETS)}")
    return toolsets


def build_server(toolsets: Iterable[str] | None = None) -> FastMCP:
    load_dotenv()  # picks up .env in the current working directory, if present
    toolsets = set(selected_toolsets() if toolsets is None else toolsets)

    # One MSAL auth shared by every httpx client built here: three clients (v1.0, beta, plus the
    # graph toolset) each owning their own token cache would mean three client-credentials
    # round-trips per startup. Also validates the AZURE_* variables up front.
    auth = build_auth()
    providers: list[OpenAPIProvider] = []
    if "xdr" in toolsets:
        # One provider per Graph version. The xdr tools build relative URLs, so each provider's
        # client must be rooted at that spec's server (v1.0 / beta); the graph toolset always sends
        # absolute URLs and works with either.
        for spec_resource in (SPEC_RESOURCE_V1, SPEC_RESOURCE_BETA):
            spec = yaml.safe_load(spec_resource.read_text())
            client = build_http_client(spec["servers"][0]["url"], auth=auth)
            providers.append(
                OpenAPIProvider(
                    openapi_spec=spec,
                    client=client,
                    route_maps=ROUTE_MAPS,
                    mcp_component_fn=_customize_component,
                )
            )

    server = FastMCP(name="defender-xdr", providers=providers)

    if "graph" in toolsets:
        register_graph_tools(server, build_http_client(f"{GRAPH_ROOT}/v1.0", auth=auth))
    return server


def main() -> None:
    build_server().run()  # stdio transport by default - Claude Code spawns this as a subprocess


if __name__ == "__main__":
    main()
